#!/usr/bin/env python3
"""Generate the viewer's alerts.js (window.ALERTS) from a slice + incident spec.

Role colours in the viewer are driven by window.ALERTS.classes[planet], with a
per-planet role and per-gate roles. We build that straight from the slice's role
tags, so the colours cannot drift from the data. Human text (summary, per-gate
notes, the narrated tour) comes from the spec's "incident" block.

    python3 analysis/gen_alerts.py \
        --slice analysis/php/slice.json \
        --spec  analysis/php/incident_php2shell.json \
        --out   diagrams/php/alerts.js
"""
import argparse
import json
import os


ROLE_RANK = {"problem": 3, "fix": 2, "path": 1}


def planet_id(path):
    return os.path.basename(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slice", required=True)
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    sl = json.load(open(args.slice))
    spec = json.load(open(args.spec))
    inc = spec["incident"]
    notes = inc.get("notes", {})

    classes = {}
    for path, info in sl["files"].items():
        pid = planet_id(path)
        gate_roles = {}
        for fn in info["functions"]:
            if fn.get("role"):
                gate_roles[fn["name"]] = {
                    "role": fn["role"],
                    "note": notes.get(fn["name"], ""),
                }
        if not gate_roles:
            continue
        # planet role = the strongest role among its tagged gates
        planet_role = max((g["role"] for g in gate_roles.values()),
                          key=lambda r: ROLE_RANK[r])
        classes[pid] = {
            "role": planet_role,
            "note": notes.get(pid, ""),
            "gates": gate_roles,
        }

    alerts = {
        "id": inc["id"],
        "cve": inc["cve"],
        "date": inc["date"],
        "fixedIn": inc["fixedIn"],
        "title": inc["title"],
        "summary": inc["summary"],
        "focus": inc.get("focus"),
        "tour": inc.get("tour", []),
        "classes": classes,
    }

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write("// Generated by analysis/gen_alerts.py from slice.json + "
                 "incident_php2shell.json. Do not edit by hand.\n")
        fh.write("// role: problem = where the bug lived (red) / "
                 "path = how it was reached (amber) / "
                 "fix = what the patch hardened (green).\n")
        fh.write("window.ALERTS = ")
        json.dump(alerts, fh, indent=1, ensure_ascii=False)
        fh.write(";\n")

    ntagged = sum(len(c["gates"]) for c in classes.values())
    print(f"{len(classes)} tagged planets, {ntagged} tagged gates, "
          f"{len(alerts['tour'])} tour scenes -> {args.out}")
    for pid, c in classes.items():
        print(f"  {c['role']:8} {pid}: "
              + ", ".join(f"{g}={v['role']}" for g, v in c["gates"].items()))


if __name__ == "__main__":
    main()
